const translations: Record<Exclude<WispLanguage, "auto">, Record<keyof typeof english, string>> = {
  en: english,
  "zh-CN": chinese
};

export type TranslationKey = keyof typeof english;

export class I18n {
  private language: WispLanguage;

  constructor(language: WispLanguage = "auto") {
    this.language = language;
  }

  setLanguage(language: WispLanguage): void {
    this.language = language;
  }

  getLanguage(): WispLanguage {
    return this.language;
  }

  t(key: TranslationKey, variables: Record<string, string> = {}): string {
    const locale = this.language === "auto" ? detectLanguage() : this.language;
    const template = translations[locale][key] ?? english[key];
    return template.replace(/\{(\w+)\}/g, (match, name: string) => variables[name] ?? match);
  }
}

function detectLanguage(): Exclude<WispLanguage, "auto"> {
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}
